#!/usr/bin/env node
/**
 * @file scripts/install-linter.mjs
 * @version 2.2.0
 * Installs the Acordismo / Small Hotel Room VS Code Linter & Syntax Decorator extension
 * directly into `~/.vscode/extensions/acordismo-song-linter`.
 *
 * Features:
 * - Zero-duplication mtime-cached loader for `smallhotelroom.github.io/src/shared/songSchema.js`
 *   and `chordTransposer.js` (auto-reloads whenever you edit songSchema.js!)
 * - Frontmatter key order & required key diagnostics
 * - Inline `(Chord)` group validation & syntax highlighting (using SYNTAX_PALETTE)
 * - Markdown `## Section` header highlighting & `## Chords` / `## Fingerings` harmonic posture validation
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

export const __version__ = '2.2.0';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const EXTERNAL_SCHEMA_PATH = path.resolve(
    ROOT_DIR,
    '../smallhotelroom.github.io/src/shared/songSchema.js'
);
const EXTERNAL_TRANSPOSER_PATH = path.resolve(
    ROOT_DIR,
    '../smallhotelroom.github.io/src/shared/chordTransposer.js'
);

if (!fs.existsSync(EXTERNAL_SCHEMA_PATH)) {
    console.error(
        `❌ Error: Master songSchema.js not found at ${EXTERNAL_SCHEMA_PATH}`
    );
    process.exit(1);
}

const EXT_DIR = path.join(
    os.homedir(),
    '.vscode',
    'extensions',
    'acordismo-song-linter'
);

const extPackageJson = {
    name: 'acordismo-song-linter',
    displayName: 'Acordismo Song Schema & Chord Linter',
    description:
        'Validates frontmatter, inline chord notation, and ## Chords / translation sections for Small Hotel Room & Acordismo song files.',
    version: __version__,
    publisher: 'smallhotelroom',
    engines: {
        vscode: '^1.75.0',
    },
    activationEvents: ['*'],
    main: './extension.cjs',
};

const extensionCjsCode = `/**
 * @file extension.cjs (Generated by scripts/install-linter.mjs)
 * @version ${__version__}
 */
const vscode = require('vscode');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const SCHEMA_PATH = ${JSON.stringify(EXTERNAL_SCHEMA_PATH)};
const TRANSPOSER_PATH = ${JSON.stringify(EXTERNAL_TRANSPOSER_PATH)};

let schemaMod = null;
let transposerMod = null;
let schemaMtime = 0;
let transposerMtime = 0;
let decorationTypes = null;

/**
 * Evaluates an ES Module file from disk inside VS Code's CommonJS extension host
 * without requiring a "type": "module" package.json in the external repository.
 */
function evaluateEsmFile(filePath, injectedModules = {}) {
    const rawCode = fs.readFileSync(filePath, 'utf8');
    const exportedNames = [];

    let transformed = rawCode
        // Replace import { a, b } from './songSchema.js' with destructuring from injectedModules
        .replace(
            /import\\s*\\{([\\s\\S]*?)\\}\\s*from\\s*['"]([^'"]+)['"];?/g,
            (_, importsBlock, spec) => {
                const bindings = importsBlock
                    .replace(/\\s+as\\s+/g, ': ')
                    .trim();
                return 'const {' + bindings + '} = __require(' + JSON.stringify(spec) + ');';
            }
        )
        .replace(/export\\s+const\\s+([a-zA-Z0-9_$]+)/g, (_, name) => {
            exportedNames.push(name);
            return 'const ' + name;
        })
        .replace(/export\\s+let\\s+([a-zA-Z0-9_$]+)/g, (_, name) => {
            exportedNames.push(name);
            return 'let ' + name;
        })
        .replace(/export\\s+function\\s+([a-zA-Z0-9_$]+)/g, (_, name) => {
            exportedNames.push(name);
            return 'function ' + name;
        })
        .replace(/export\\s*\\{([\\s\\S]*?)\\};?/g, (_, block) => {
            block
                .split(',')
                .map((s) => s.trim())
                .filter(Boolean)
                .forEach((s) => exportedNames.push(s));
            return '';
        });

    transformed +=
        '\\nmodule.exports = { ' + exportedNames.join(', ') + ' };\\n';

    const mod = { exports: {} };
    const sandbox = {
        module: mod,
        exports: mod.exports,
        console,
        Set,
        Map,
        Object,
        Array,
        String,
        Number,
        Boolean,
        Math,
        RegExp,
        JSON,
        parseInt,
        parseFloat,
        isNaN,
        __require: (spec) => {
            if (spec.includes('songSchema')) {
                return injectedModules.songSchema;
            }
            return {};
        },
    };
    vm.runInNewContext(transformed, sandbox, { filename: filePath });
    return mod.exports;
}

function createDecorationTypes(SYNTAX_PALETTE) {
    const dark = SYNTAX_PALETTE.dark;
    const light = SYNTAX_PALETTE.light;

    return {
        parenBg: vscode.window.createTextEditorDecorationType({
            dark: { backgroundColor: dark.parenBg, borderRadius: '3px' },
            light: { backgroundColor: light.parenBg, borderRadius: '3px' },
        }),
        parenSymbol: vscode.window.createTextEditorDecorationType({
            fontWeight: 'bold',
            dark: { color: dark.parenSymbol },
            light: { color: light.parenSymbol },
        }),
        chord: vscode.window.createTextEditorDecorationType({
            fontWeight: 'bold',
            dark: { color: dark.chord },
            light: { color: light.chord },
        }),
        modifier: vscode.window.createTextEditorDecorationType({
            fontWeight: 'bold',
            dark: { color: dark.modifier },
            light: { color: light.modifier },
        }),
        directive: vscode.window.createTextEditorDecorationType({
            fontWeight: 'bold',
            dark: { color: dark.directive },
            light: { color: light.directive },
        }),
        choir: vscode.window.createTextEditorDecorationType({
            fontStyle: 'italic',
            dark: { color: dark.choir },
            light: { color: light.choir },
        }),
    };
}

function disposeDecorations() {
    if (!decorationTypes) return;
    Object.values(decorationTypes).forEach((d) => d.dispose());
    decorationTypes = null;
}

function ensureModulesFresh() {
    try {
        const sStat = fs.statSync(SCHEMA_PATH);
        const tStat = fs.statSync(TRANSPOSER_PATH);
        if (!schemaMod || sStat.mtimeMs !== schemaMtime || tStat.mtimeMs !== transposerMtime) {
            schemaMod = evaluateEsmFile(SCHEMA_PATH);
            transposerMod = evaluateEsmFile(TRANSPOSER_PATH, { songSchema: schemaMod });
            schemaMtime = sStat.mtimeMs;
            transposerMtime = tStat.mtimeMs;
            disposeDecorations();
            if (schemaMod.SYNTAX_PALETTE) {
                decorationTypes = createDecorationTypes(schemaMod.SYNTAX_PALETTE);
            }
        }
    } catch (err) {
        console.error('Acordismo Linter failed to load shared schema:', err);
    }
}

function isCandidateSongDocument(doc) {
    if (!doc) return false;
    const fsPath = doc.uri.fsPath || '';
    const ext = path.extname(fsPath).toLowerCase();
    if (ext !== '.md' && ext !== '.txt') return false;
    const base = path.basename(fsPath, ext);
    return base.includes(' - ') || doc.getText().startsWith('---\\n');
}

function clampLineIdx(lineIdx, doc) {
    return Math.max(0, Math.min(doc.lineCount - 1, lineIdx));
}

function lintAndDecorateEditor(editor, diagnosticCollection) {
    if (!editor) return;
    ensureModulesFresh();
    if (!schemaMod || !transposerMod || !decorationTypes) return;

    const doc = editor.document;
    if (!isCandidateSongDocument(doc)) {
        diagnosticCollection.delete(doc.uri);
        return;
    }

    try {
        const rawText = doc.getText();
        const ext = path.extname(doc.uri.fsPath || '');
        const rawFileName = path.basename(doc.uri.fsPath || '', ext);

        const {
            hasFrontmatter,
            data: frontmatterData,
            keyLines,
            bodyStartLine,
            content: bodyContent,
        } = schemaMod.parseFrontmatterFile(rawText);

        const diagnostics = [];

        // 1. Validate Frontmatter (if present)
        if (hasFrontmatter) {
            const missing = schemaMod.getMissingKeys(frontmatterData, rawFileName);
            if (missing.length > 0) {
                diagnostics.push(
                    new vscode.Diagnostic(
                        new vscode.Range(0, 0, 0, 3),
                        'Missing required frontmatter keys: ' + missing.join(', '),
                        vscode.DiagnosticSeverity.Error
                    )
                );
            }

            const keys = Object.keys(frontmatterData);
            const { isValid, expected } = schemaMod.validateAlphabeticalOrder(keys);
            if (!isValid) {
                for (let i = 0; i < keys.length; i++) {
                    if (keys[i] !== expected[i]) {
                        const badKey = keys[i];
                        const lineIdx = clampLineIdx((keyLines[badKey] || 2) - 1, doc);
                        const lineText = doc.lineAt(lineIdx).text;
                        diagnostics.push(
                            new vscode.Diagnostic(
                                new vscode.Range(lineIdx, 0, lineIdx, lineText.length),
                                "Frontmatter key '" +
                                    badKey +
                                    "' is out of alphabetical order (expected '" +
                                    expected[i] +
                                    "').",
                                vscode.DiagnosticSeverity.Error
                            )
                        );
                        break;
                    }
                }
            }

            const treatedSet = new Set(schemaMod.TREATED_KEYS || []);
            for (const k of keys) {
                if (!treatedSet.has(k)) {
                    const lineIdx = clampLineIdx((keyLines[k] || 2) - 1, doc);
                    diagnostics.push(
                        new vscode.Diagnostic(
                            new vscode.Range(lineIdx, 0, lineIdx, k.length),
                            "Unknown frontmatter key '" + k + "' (not in TREATED_KEYS).",
                            vscode.DiagnosticSeverity.Warning
                        )
                    );
                }
            }
        }

        // 2. Validate Markdown ## Sections & ## Chords / ## Fingerings definitions
        if (typeof schemaMod.validateMarkdownSections === 'function') {
            const secDiags = schemaMod.validateMarkdownSections(bodyContent, bodyStartLine);
            for (const sd of secDiags) {
                const lineIdx = clampLineIdx(sd.line - 1, doc);
                const lineText = doc.lineAt(lineIdx).text;
                diagnostics.push(
                    new vscode.Diagnostic(
                        new vscode.Range(lineIdx, 0, lineIdx, Math.max(1, lineText.length)),
                        sd.message,
                        vscode.DiagnosticSeverity.Error
                    )
                );
            }
        }

        // 3. Scan Body Lines for Syntax Highlighting & Inline Chord Group Diagnostics
        const rangesParenBg = [];
        const rangesParenSymbol = [];
        const rangesChord = [];
        const rangesModifier = [];
        const rangesDirective = [];
        const rangesChoir = [];

        const bodyLines = bodyContent.split('\\n');
        let currentSectionType = 'main';

        const {
            CHORD_GROUP_DELIMITER_REGEX,
            DIRECTIVE_PAREN_REGEX,
            SECTION_HEADER_REGEX,
            FINGERING_SECTION_HEADER_REGEX,
            NOTES_SECTION_HEADER_REGEX,
            parseFingeringDefinitionLine,
        } = schemaMod;
        const { isValidParenChordGroup } = transposerMod;

        for (let i = 0; i < bodyLines.length; i++) {
            const lineText = bodyLines[i];
            const docLineIdx = bodyStartLine - 1 + i;
            if (docLineIdx < 0 || docLineIdx >= doc.lineCount) continue;

            if (lineText.startsWith('##')) {
                const secMatch = SECTION_HEADER_REGEX
                    ? SECTION_HEADER_REGEX.exec(lineText)
                    : /^##\\s+(.+?)\\s*$/.exec(lineText);
                rangesDirective.push(
                    new vscode.Range(docLineIdx, 0, docLineIdx, lineText.length)
                );
                if (secMatch) {
                    const secTitle = secMatch[1].trim();
                    if (
                        FINGERING_SECTION_HEADER_REGEX &&
                        FINGERING_SECTION_HEADER_REGEX.test(secTitle)
                    ) {
                        currentSectionType = 'fingerings';
                    } else if (
                        NOTES_SECTION_HEADER_REGEX &&
                        NOTES_SECTION_HEADER_REGEX.test(secTitle)
                    ) {
                        currentSectionType = 'notes';
                    } else {
                        currentSectionType = 'translation';
                    }
                }
                continue;
            }

            if (currentSectionType === 'fingerings') {
                const colonIdx = lineText.indexOf(':');
                if (colonIdx !== -1 && typeof parseFingeringDefinitionLine === 'function') {
                    const parsedFingering = parseFingeringDefinitionLine(lineText);
                    if (parsedFingering && parsedFingering.valid) {
                        const leftPart = lineText.slice(0, colonIdx);
                        const chordMatch = /^(\\s*)(\\S+)(?:(\\s+)(\\([^)]+\\)))?/.exec(leftPart);
                        if (chordMatch) {
                            const cStart = chordMatch[1].length;
                            const cEnd = cStart + chordMatch[2].length;
                            rangesChord.push(
                                new vscode.Range(docLineIdx, cStart, docLineIdx, cEnd)
                            );
                            if (chordMatch[4]) {
                                const pStart = cEnd + (chordMatch[3] ? chordMatch[3].length : 0);
                                const pEnd = pStart + chordMatch[4].length;
                                rangesParenSymbol.push(
                                    new vscode.Range(docLineIdx, pStart, docLineIdx, pEnd)
                                );
                            }
                        }

                        rangesParenSymbol.push(
                            new vscode.Range(docLineIdx, colonIdx, docLineIdx, colonIdx + 1)
                        );
                        const rightPart = lineText.slice(colonIdx + 1);
                        const quoteMatch = /^(.*?)(\\s+["'].+["']\\s*)$/.exec(rightPart);
                        if (quoteMatch) {
                            const fretsEnd = colonIdx + 1 + quoteMatch[1].length;
                            rangesModifier.push(
                                new vscode.Range(docLineIdx, colonIdx + 1, docLineIdx, fretsEnd)
                            );
                            rangesChoir.push(
                                new vscode.Range(
                                    docLineIdx,
                                    fretsEnd,
                                    docLineIdx,
                                    colonIdx + 1 + rightPart.length
                                )
                            );
                        } else {
                            rangesModifier.push(
                                new vscode.Range(
                                    docLineIdx,
                                    colonIdx + 1,
                                    docLineIdx,
                                    lineText.length
                                )
                            );
                        }
                    }
                }
                continue;
            }

            const choirRe = /\\[[^\\]]+\\]/g;
            let cMatch;
            while ((cMatch = choirRe.exec(lineText)) !== null) {
                rangesChoir.push(
                    new vscode.Range(
                        docLineIdx,
                        cMatch.index,
                        docLineIdx,
                        cMatch.index + cMatch[0].length
                    )
                );
            }

            const parenRe = /\\((.+?)\\)/g;
            let pMatch;
            while ((pMatch = parenRe.exec(lineText)) !== null) {
                const fullStart = pMatch.index;
                const fullEnd = pMatch.index + pMatch[0].length;
                const innerGroup = pMatch[1];
                const innerStart = fullStart + 1;

                const isDirective = DIRECTIVE_PAREN_REGEX.test(innerGroup);
                if (isDirective) {
                    rangesDirective.push(
                        new vscode.Range(docLineIdx, fullStart, docLineIdx, fullEnd)
                    );
                    continue;
                }

                if (isValidParenChordGroup(innerGroup)) {
                    rangesParenBg.push(
                        new vscode.Range(docLineIdx, fullStart, docLineIdx, fullEnd)
                    );
                    rangesParenSymbol.push(
                        new vscode.Range(docLineIdx, fullStart, docLineIdx, fullStart + 1)
                    );
                    rangesParenSymbol.push(
                        new vscode.Range(docLineIdx, fullEnd - 1, docLineIdx, fullEnd)
                    );

                    let remaining = innerGroup;
                    let offset = 0;
                    while (remaining.length > 0) {
                        const delim = CHORD_GROUP_DELIMITER_REGEX.exec(remaining);
                        if (delim !== null) {
                            const treatable = remaining.slice(0, delim.index);
                            const delimStr = delim[0];
                            if (treatable.length > 0) {
                                rangesChord.push(
                                    new vscode.Range(
                                        docLineIdx,
                                        innerStart + offset,
                                        docLineIdx,
                                        innerStart + offset + treatable.length
                                    )
                                );
                            }
                            rangesModifier.push(
                                new vscode.Range(
                                    docLineIdx,
                                    innerStart + offset + delim.index,
                                    docLineIdx,
                                    innerStart + offset + delim.index + delimStr.length
                                )
                            );
                            const step = delim.index + delimStr.length;
                            remaining = remaining.slice(step);
                            offset += step;
                        } else {
                            rangesChord.push(
                                new vscode.Range(
                                    docLineIdx,
                                    innerStart + offset,
                                    docLineIdx,
                                    innerStart + offset + remaining.length
                                )
                            );
                            break;
                        }
                    }
                } else if (currentSectionType === 'main') {
                    if (/^[A-G][#b]?/.test(innerGroup.trim())) {
                        diagnostics.push(
                            new vscode.Diagnostic(
                                new vscode.Range(docLineIdx, fullStart, docLineIdx, fullEnd),
                                "Invalid chord group '(" +
                                    innerGroup +
                                    ")'. Check chord token spelling or delimiter spacing.",
                                vscode.DiagnosticSeverity.Warning
                            )
                        );
                    }
                }
            }
        }

        diagnosticCollection.set(doc.uri, diagnostics);
        editor.setDecorations(decorationTypes.parenBg, rangesParenBg);
        editor.setDecorations(decorationTypes.parenSymbol, rangesParenSymbol);
        editor.setDecorations(decorationTypes.chord, rangesChord);
        editor.setDecorations(decorationTypes.modifier, rangesModifier);
        editor.setDecorations(decorationTypes.directive, rangesDirective);
        editor.setDecorations(decorationTypes.choir, rangesChoir);
    } catch (err) {
        console.error('Acordismo Linter error:', err);
    }
}

function activate(context) {
    ensureModulesFresh();
    const diagnosticCollection =
        vscode.languages.createDiagnosticCollection('acordismo-song-linter');
    context.subscriptions.push(diagnosticCollection);

    const triggerUpdate = (editor) => {
        if (editor) {
            lintAndDecorateEditor(editor, diagnosticCollection);
        }
    };

    if (vscode.window.activeTextEditor) {
        triggerUpdate(vscode.window.activeTextEditor);
    }

    context.subscriptions.push(
        vscode.window.onDidChangeActiveTextEditor((editor) => triggerUpdate(editor)),
        vscode.workspace.onDidChangeTextDocument((e) => {
            const active = vscode.window.activeTextEditor;
            if (active && e.document === active.document) {
                triggerUpdate(active);
            }
        })
    );
}

function deactivate() {
    disposeDecorations();
}

module.exports = { activate, deactivate };
`;

fs.mkdirSync(EXT_DIR, { recursive: true });
fs.writeFileSync(
    path.join(EXT_DIR, 'package.json'),
    JSON.stringify(extPackageJson, null, 2),
    'utf8'
);
fs.writeFileSync(path.join(EXT_DIR, 'extension.cjs'), extensionCjsCode, 'utf8');

console.log(`✅ Installed Acordismo Song Linter v${__version__} to:`);
console.log(`   ${EXT_DIR}`);
console.log(
    `💡 Reload VS Code ('Developer: Reload Window') to activate live harmonic posture linting!`
);
